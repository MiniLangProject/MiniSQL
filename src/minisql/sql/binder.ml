// Finds column index using the supplied inputs.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function findColumnIndex(table, name)
  if table is void then return -1 end if
  if not metadata.isTableMetadata(table) then return fail(INVALID_ARGUMENT, "findColumnIndex", "table must be TableMetadata") end if
  if typeof(name) != "string" then return fail(INVALID_ARGUMENT, "findColumnIndex", "name must be string") end if
  if len(table.columns) > 0 then
    for index = 0 to len(table.columns) - 1
      if table.columns[index].name == name then return index end if
    end for
  end if
  return -1
end function

// Finds column using the supplied inputs.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function findColumn(table, name)
  index = findColumnIndex(table, name)
  if index < 0 then return void end if
  return table.columns[index]
end function

// Implements literal type for this module.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function literalType(value)
  nullable = value.isNull
  if value.typeKind == types.SqlTypeKind.Unknown then return types.create(types.SqlTypeKind.Integer, 0, 0, 0, true) end if
  if types.isTextKind(value.typeKind) then return types.create(types.SqlTypeKind.Text, 0, 0, 0, nullable) end if
  if types.isBinaryKind(value.typeKind) then return types.create(types.SqlTypeKind.Blob, 0, 0, 0, nullable) end if
  return types.create(value.typeKind, 0, 0, 0, nullable)
end function

// Binds literal using the supplied inputs.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function bindLiteral(expression)
  if expression.literalKind == ast.LITERAL_CURRENT_TIMESTAMP then
    typeInfo = types.create(types.SqlTypeKind.Timestamp, 0, 6, 0, false)
    return expressions.literal(values.of(types.SqlTypeKind.Timestamp, endian.int64FromInt(0)), typeInfo)
  end if
  value = values.fromLiteral(expression)
  return expressions.literal(value, literalType(value))
end function

// Implements source visible name for this module.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function sourceVisibleName(source)
  if source.alias is not void then return source.alias end if
  raw = bytes(source.table.name)
  lastDot = -1
  if len(raw) > 0 then
    for index = 0 to len(raw) - 1
      if raw[index] == 46 then lastDot = index end if
    end for
  end if
  if lastDot >= 0 then return decode(slice(raw, lastDot + 1, len(raw) - lastDot - 1)) end if
  return source.table.name
end function

// Returns the unqualified component of a canonical schema-qualified object name.
function objectLocalName(name)
  raw = bytes(name)
  lastDot = -1
  if len(raw) > 0 then
    for index = 0 to len(raw) - 1
      if raw[index] == 46 then lastDot = index end if
    end for
  end if
  if lastDot >= 0 then return decode(slice(raw, lastDot + 1, len(raw) - lastDot - 1)) end if
  return name
end function

// Keeps an unqualified ALTER TABLE rename inside the table's current schema.
function schemaPreservingRename(currentName, newLocalName)
  raw = bytes(currentName)
  lastDot = -1
  if len(raw) > 0 then
    for index = 0 to len(raw) - 1
      if raw[index] == 46 then lastDot = index end if
    end for
  end if
  if lastDot < 0 then return newLocalName end if
  return decode(slice(raw, 0, lastDot + 1)) + newLocalName
end function

