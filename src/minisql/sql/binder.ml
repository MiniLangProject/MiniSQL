// Implements merge concrete types for this module.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function mergeConcreteTypes(left, right)
  if types.isNumeric(left) and types.isNumeric(right) then return types.commonNumeric(left, right) end if
  if types.isTextKind(left.kind) and types.isTextKind(right.kind) then return types.create(types.SqlTypeKind.Text, 0, 0, 0, left.nullable or right.nullable) end if
  if types.isBinaryKind(left.kind) and types.isBinaryKind(right.kind) then return types.create(types.SqlTypeKind.Blob, 0, 0, 0, left.nullable or right.nullable) end if
  if left.kind == right.kind then
    length = left.length
    if right.length > length then length = right.length end if
    precision = left.precision
    if right.precision > precision then precision = right.precision end if
    scale = left.scale
    if right.scale > scale then scale = right.scale end if
    return types.create(left.kind, length, precision, scale, left.nullable or right.nullable)
  end if
  return fail(TYPE_MISMATCH, "mergeConcreteTypes", "CASE/COALESCE result types are incompatible")
end function

// Implements merge result type for this module.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function mergeResultType(currentType, hasConcrete, nextExpression)
  if isNullBoundLiteral(nextExpression) then
    if currentType is void then currentType = types.create(types.SqlTypeKind.Integer, 0, 0, 0, true) else currentType = resultTypeWithNullability(currentType, true) end if
    return [currentType, hasConcrete]
  end if
  if not hasConcrete then
    nullable = nextExpression.typeInfo.nullable
    if currentType is not void and currentType.nullable then nullable = true end if
    return [resultTypeWithNullability(nextExpression.typeInfo, nullable), true]
  end if
  return [mergeConcreteTypes(currentType, nextExpression.typeInfo), true]
end function

// Binds scalar function using the supplied inputs.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function bindScalarFunction(expression, sources, allowAggregates, database)
  name = expression.name
  if name == "COALESCE" then
    if len(expression.arguments) < 1 then return fail(BINDING_ERROR, "bindScalarFunction", "COALESCE requires at least one argument") end if
    arguments = []
    resultType = void
    hasConcrete = false
    for each argumentAst in expression.arguments
      argument = bindExpressionInternal(argumentAst, sources, allowAggregates, database)
      merged = mergeResultType(resultType, hasConcrete, argument)
      resultType = merged[0]
      hasConcrete = merged[1]
      arguments = arguments + [argument]
    end for
    if resultType is void then resultType = types.create(types.SqlTypeKind.Integer, 0, 0, 0, true) end if
    nullable = true
    for each argument in arguments
      if not argument.typeInfo.nullable and not isNullBoundLiteral(argument) then nullable = false end if
    end for
    resultType = resultTypeWithNullability(resultType, nullable)
    return expressions.scalar(name, arguments, resultType)
  end if
  if name == "NULLIF" then
    if len(expression.arguments) != 2 then return fail(BINDING_ERROR, "bindScalarFunction", "NULLIF requires exactly two arguments") end if
    left = bindExpressionInternal(expression.arguments[0], sources, allowAggregates, database)
    right = bindExpressionInternal(expression.arguments[1], sources, allowAggregates, database)
    if not isNullBoundLiteral(left) and not isNullBoundLiteral(right) and not types.comparable(left.typeInfo, right.typeInfo) then return fail(TYPE_MISMATCH, "bindScalarFunction", "NULLIF arguments are incompatible") end if
    return expressions.scalar(name, [left, right], resultTypeWithNullability(left.typeInfo, true))
  end if
  arguments = []
  for each argumentAst in expression.arguments
    arguments = arguments + [bindExpressionInternal(argumentAst, sources, allowAggregates, database)]
  end for
  if name == "LOWER" or name == "UPPER" or name == "LENGTH" or name == "CHAR_LENGTH" or name == "TRIM" then
    if len(arguments) != 1 then return fail(BINDING_ERROR, "bindScalarFunction", name + " requires exactly one argument") end if
    if not types.isTextKind(arguments[0].typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", name + " requires text") end if
    if name == "LENGTH" or name == "CHAR_LENGTH" then return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Integer, 0, 0, 0, arguments[0].typeInfo.nullable)) end if
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Text, 0, 0, 0, arguments[0].typeInfo.nullable))
  end if
  if name == "SUBSTRING" then
    if len(arguments) != 2 and len(arguments) != 3 then return fail(BINDING_ERROR, "bindScalarFunction", "SUBSTRING requires text, start and optional length") end if
    if not types.isTextKind(arguments[0].typeInfo.kind) or not types.isIntegralKind(arguments[1].typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", "SUBSTRING requires text and an integral start") end if
    if len(arguments) == 3 and not types.isIntegralKind(arguments[2].typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", "SUBSTRING length must be integral") end if
    nullable = arguments[0].typeInfo.nullable or arguments[1].typeInfo.nullable
    if len(arguments) == 3 then nullable = nullable or arguments[2].typeInfo.nullable end if
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Text, 0, 0, 0, nullable))
  end if
  if name == "REPLACE" then
    if len(arguments) != 3 then return fail(BINDING_ERROR, "bindScalarFunction", "REPLACE requires three text arguments") end if
    nullable = false
    for each argument in arguments
      if not types.isTextKind(argument.typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", "REPLACE requires text arguments") end if
      nullable = nullable or argument.typeInfo.nullable
    end for
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Text, 0, 0, 0, nullable))
  end if
  if name == "CONCAT" then
    if len(arguments) < 1 then return fail(BINDING_ERROR, "bindScalarFunction", "CONCAT requires at least one argument") end if
    nullable = false
    for each argument in arguments
      if not types.isTextKind(argument.typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", "CONCAT requires text arguments") end if
      nullable = nullable or argument.typeInfo.nullable
    end for
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Text, 0, 0, 0, nullable))
  end if
  if name == "ABS" or name == "ROUND" or name == "CEIL" or name == "FLOOR" then
    if len(arguments) != 1 or not types.isNumeric(arguments[0].typeInfo) then return fail(TYPE_MISMATCH, "bindScalarFunction", name + " requires one numeric argument") end if
    if name != "ABS" and arguments[0].typeInfo.kind == types.SqlTypeKind.Decimal then return fail(UNSUPPORTED_SQL, "bindScalarFunction", name + " for DECIMAL requires scale-aware rounding") end if
    return expressions.scalar(name, arguments, arguments[0].typeInfo)
  end if
  if name == "POWER" then
    if len(arguments) != 2 or not types.isNumeric(arguments[0].typeInfo) or not types.isNumeric(arguments[1].typeInfo) then return fail(TYPE_MISMATCH, "bindScalarFunction", "POWER requires two numeric arguments") end if
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Double, 0, 0, 0, arguments[0].typeInfo.nullable or arguments[1].typeInfo.nullable))
  end if
  if name == "DATE_PART" then
    if len(arguments) != 2 or not types.isTextKind(arguments[0].typeInfo.kind) then return fail(TYPE_MISMATCH, "bindScalarFunction", "DATE_PART requires a text part and temporal value") end if
    temporalKind = arguments[1].typeInfo.kind
    if temporalKind != types.SqlTypeKind.Date and temporalKind != types.SqlTypeKind.Time and temporalKind != types.SqlTypeKind.Timestamp then return fail(TYPE_MISMATCH, "bindScalarFunction", "DATE_PART value must be DATE, TIME or TIMESTAMP") end if
    return expressions.scalar(name, arguments, types.create(types.SqlTypeKind.Integer, 0, 0, 0, arguments[0].typeInfo.nullable or arguments[1].typeInfo.nullable))
  end if
  return fail(BINDING_ERROR, "bindScalarFunction", "unsupported scalar function " + name)
end function

// Binds aggregate using the supplied inputs.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function bindAggregate(expression, sources, database)
  name = expression.name
  if name == "STRING_AGG" then
    if len(expression.arguments) != 2 then return fail(BINDING_ERROR, "bindAggregate", "STRING_AGG requires value and delimiter") end if
    argument = bindExpressionInternal(expression.arguments[0], sources, false, database)
    separator = bindExpressionInternal(expression.arguments[1], sources, false, database)
    if not types.isTextKind(argument.typeInfo.kind) or not types.isTextKind(separator.typeInfo.kind) then return fail(TYPE_MISMATCH, "bindAggregate", "STRING_AGG requires text arguments") end if
    if expressions.containsAggregate(argument) or expressions.containsAggregate(separator) then return fail(BINDING_ERROR, "bindAggregate", "nested aggregates are not supported") end if
    return expressions.aggregate(name, argument, separator, expression.distinct, types.create(types.SqlTypeKind.Text, 0, 0, 0, true), false)
  end if
  if name != "COUNT" and name != "SUM" and name != "AVG" and name != "MIN" and name != "MAX" and name != "BOOL_AND" and name != "BOOL_OR" then return fail(BINDING_ERROR, "bindAggregate", "unsupported aggregate " + name) end if
  if len(expression.arguments) != 1 then return fail(BINDING_ERROR, "bindAggregate", name + " requires exactly one argument") end if
  argumentAst = expression.arguments[0]
  countStar = name == "COUNT" and ast.isStarExpression(argumentAst)
  if ast.isStarExpression(argumentAst) and not countStar then return fail(BINDING_ERROR, "bindAggregate", "only COUNT accepts *") end if
  if countStar and expression.distinct then return fail(BINDING_ERROR, "bindAggregate", "COUNT(DISTINCT *) is invalid") end if
  if countStar then return expressions.aggregate(name, void, void, false, types.create(types.SqlTypeKind.BigInt, 0, 0, 0, false), true) end if
  argument = bindExpressionInternal(argumentAst, sources, false, database)
  if expressions.containsAggregate(argument) then return fail(BINDING_ERROR, "bindAggregate", "nested aggregates are not supported") end if
  resultType = argument.typeInfo
  if name == "COUNT" then
    resultType = types.create(types.SqlTypeKind.BigInt, 0, 0, 0, false)
  else if name == "SUM" then
    if not types.isNumeric(argument.typeInfo) then return fail(TYPE_MISMATCH, "bindAggregate", "SUM requires a numeric argument") end if
    if types.isIntegralKind(argument.typeInfo.kind) then resultType = types.create(types.SqlTypeKind.BigInt, 0, 0, 0, true) end if
  else if name == "AVG" then
    if not types.isNumeric(argument.typeInfo) then return fail(TYPE_MISMATCH, "bindAggregate", "AVG requires a numeric argument") end if
    resultType = types.create(types.SqlTypeKind.Double, 0, 0, 0, true)
  else if name == "BOOL_AND" or name == "BOOL_OR" then
    if argument.typeInfo.kind != types.SqlTypeKind.Boolean then return fail(TYPE_MISMATCH, "bindAggregate", name + " requires BOOLEAN") end if
    resultType = types.create(types.SqlTypeKind.Boolean, 0, 0, 0, true)
  else
    resultType = types.withNullable(argument.typeInfo, true)
  end if
  return expressions.aggregate(name, argument, void, expression.distinct, resultType, false)
end function

// Returns true when a qualifier belongs to a source declared by this nested SELECT.
// Such names shadow outer aliases and must remain ordinary inner-column references.
function selectDeclaresQualifier(statement, qualifier)
  if statement.tableName is not void then
    if statement.tableName == qualifier or objectLocalName(statement.tableName) == qualifier or statement.tableAlias == qualifier then return true end if
  end if
  for each joinClause in statement.joins
    if joinClause.tableName == qualifier or objectLocalName(joinClause.tableName) == qualifier or joinClause.tableAlias == qualifier then return true end if
  end for
  for each cte in statement.ctes
    if cte.name == qualifier then return true end if
  end for
  return false
end function

// Replaces an explicitly qualified outer-column reference with a typed NULL.
// The placeholder lets the ordinary nested-query binder infer and validate its
// output shape without depending on a concrete outer row.
function maskOuterColumn(expression, sources, statement)
  if expression.qualifier is void or selectDeclaresQualifier(statement, expression.qualifier) then return expression end if
  for each source in sources
    if expression.qualifier == sourceVisibleName(source) or expression.qualifier == source.table.name then
      columnIndex = findColumnIndex(source.table, expression.name)
      if columnIndex < 0 then return fail(BINDING_ERROR, "bindSubquery", "unknown outer column " + expression.qualifier + "." + expression.name) end if
      columnType = types.fromColumn(source.table.columns[columnIndex])
      return ast.typedLiteralExpression(values.nullValue(columnType.kind))
    end if
  end for
  return expression
end function

// Recursively masks outer references throughout one nested expression tree.
function maskOuterExpression(expression, sources, statement)
  if ast.isColumnExpression(expression) then return maskOuterColumn(expression, sources, statement) end if
  if ast.isLiteralExpression(expression) or ast.isTypedLiteralExpression(expression) or ast.isStarExpression(expression) or ast.isParameterExpression(expression) then return expression end if
  if ast.isUnaryExpression(expression) then return ast.unaryExpression(expression.operator, maskOuterExpression(expression.operand, sources, statement)) end if
  if ast.isBinaryExpression(expression) then return ast.binaryExpression(expression.operator, maskOuterExpression(expression.left, sources, statement), maskOuterExpression(expression.right, sources, statement)) end if
  if ast.isIsNullExpression(expression) then return ast.isNullExpression(maskOuterExpression(expression.operand, sources, statement), expression.negated) end if
  if ast.isCaseExpression(expression) then
    branches = []
    for each branch in expression.branches
      branches = branches + [ast.caseBranch(maskOuterExpression(branch.condition, sources, statement), maskOuterExpression(branch.result, sources, statement))]
    end for
    elseExpression = void
    if expression.elseExpression is not void then elseExpression = maskOuterExpression(expression.elseExpression, sources, statement) end if
    return ast.caseExpression(branches, elseExpression)
  end if
  if ast.isCastExpression(expression) then return ast.castExpression(maskOuterExpression(expression.operand, sources, statement), expression.targetType) end if
  if ast.isInExpression(expression) then
    candidates = []
    for each candidate in expression.values
      candidates = candidates + [maskOuterExpression(candidate, sources, statement)]
    end for
    return ast.inExpression(maskOuterExpression(expression.operand, sources, statement), candidates, expression.negated)
  end if
  if ast.isBetweenExpression(expression) then return ast.betweenExpression(maskOuterExpression(expression.operand, sources, statement), maskOuterExpression(expression.lower, sources, statement), maskOuterExpression(expression.upper, sources, statement), expression.negated) end if
  if ast.isTruthTestExpression(expression) then return ast.truthTestExpression(maskOuterExpression(expression.operand, sources, statement), expression.expected, expression.negated) end if
  if ast.isFunctionExpression(expression) then
    arguments = []
    for each argument in expression.arguments
      arguments = arguments + [maskOuterExpression(argument, sources, statement)]
    end for
    return ast.functionExpression(expression.name, arguments, expression.distinct)
  end if
  if ast.isSubqueryExpression(expression) then return ast.subqueryExpression(maskOuterSelect(expression.query, sources)) end if
  if ast.isExistsExpression(expression) then return ast.existsExpression(maskOuterSelect(expression.query, sources)) end if
  if ast.isInSubqueryExpression(expression) then return ast.inSubqueryExpression(maskOuterExpression(expression.operand, sources, statement), maskOuterSelect(expression.query, sources), expression.negated) end if
  if ast.isWindowExpression(expression) then
    arguments = []
    partitions = []
    orders = []
    for each argument in expression.arguments
      arguments = arguments + [maskOuterExpression(argument, sources, statement)]
    end for
    for each value in expression.partitionBy
      partitions = partitions + [maskOuterExpression(value, sources, statement)]
    end for
    for each value in expression.orderBy
      orders = orders + [ast.OrderItem(maskOuterExpression(value.expression, sources, statement), value.descending, value.nullsFirst, value.nullsSpecified)]
    end for
    return ast.windowExpression(expression.name, arguments, partitions, orders)
  end if
  return fail(BINDING_ERROR, "bindSubquery", "unsupported nested expression")
end function

// Copies a nested SELECT while replacing only references resolved against outer sources.
function maskOuterSelect(statement, sources)
  items = []
  for each item in statement.items
    items = items + [ast.SelectItem(maskOuterExpression(item.expression, sources, statement), item.alias)]
  end for
  joins = []
  for each value in statement.joins
    condition = void
    if value.condition is not void then condition = maskOuterExpression(value.condition, sources, statement) end if
    joins = joins + [ast.JoinClause(value.joinType, value.tableName, value.tableAlias, condition)]
  end for
  whereExpression = void
  if statement.whereExpression is not void then whereExpression = maskOuterExpression(statement.whereExpression, sources, statement) end if
  groups = []
  for each value in statement.groupBy
    groups = groups + [maskOuterExpression(value, sources, statement)]
  end for
  havingExpression = void
  if statement.havingExpression is not void then havingExpression = maskOuterExpression(statement.havingExpression, sources, statement) end if
  setOperations = []
  for each value in statement.setOperations
    setOperations = setOperations + [ast.SetOperation(value.operator, value.all, maskOuterSelect(value.query, sources))]
  end for
  orderBy = []
  for each value in statement.orderBy
    orderBy = orderBy + [ast.OrderItem(maskOuterExpression(value.expression, sources, statement), value.descending, value.nullsFirst, value.nullsSpecified)]
  end for
  ctes = []
  for each cte in statement.ctes
    ctes = ctes + [ast.CommonTableExpression(cte.name, maskOuterSelect(cte.query, sources), cte.columnNames, cte.recursive)]
  end for
  return ast.SelectStatement(statement.distinct, items, statement.tableName, statement.tableAlias, joins, whereExpression, groups, havingExpression, setOperations, orderBy, statement.limit, statement.offset, ctes)
end function

// Binds expression internal using the supplied inputs.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function bindExpressionInternal(expression, sources, allowAggregates, database)
  if ast.isTypedLiteralExpression(expression) then return expressions.literal(expression.value, literalType(expression.value)) end if
  if ast.isLiteralExpression(expression) then return bindLiteral(expression) end if
  if ast.isColumnExpression(expression) then return bindColumnSources(expression, sources) end if
  if ast.isStarExpression(expression) then return fail(BINDING_ERROR, "bindExpression", "'*' is valid only as a SELECT item or COUNT(*)") end if
  if ast.isSubqueryExpression(expression) or ast.isExistsExpression(expression) or ast.isInSubqueryExpression(expression) then
    if database is void then return fail(BINDING_ERROR, "bindSubquery", "subqueries are not supported in this statement context") end if
    query = maskOuterSelect(expression.query, sources)
    nested = bindSelect(query, database)
    if ast.isExistsExpression(expression) then return expressions.subquery(expressions.SUBQUERY_EXISTS, expression.query, void, false, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, false)) end if
    if len(nested.items) != 1 then return fail(BINDING_ERROR, "bindSubquery", "subquery must return exactly one column") end if
    if ast.isSubqueryExpression(expression) then return expressions.subquery(expressions.SUBQUERY_SCALAR, expression.query, void, false, resultTypeWithNullability(nested.items[0].typeInfo, true)) end if
    operand = bindExpressionInternal(expression.operand, sources, allowAggregates, database)
    if not types.comparable(operand.typeInfo, nested.items[0].typeInfo) then return fail(TYPE_MISMATCH, "bindSubquery", "IN operand and subquery column are incompatible") end if
    return expressions.subquery(expressions.SUBQUERY_IN, expression.query, operand, expression.negated, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, true))
  end if
  if ast.isWindowExpression(expression) then
    name = expression.name
    ranking = name == "ROW_NUMBER" or name == "RANK" or name == "DENSE_RANK" or name == "PERCENT_RANK" or name == "CUME_DIST"
    navigation = name == "NTILE" or name == "LAG" or name == "LEAD" or name == "FIRST_VALUE" or name == "LAST_VALUE" or name == "NTH_VALUE"
    supported = ranking or navigation or isWindowAggregateName(name)
    if not supported then return fail(BINDING_ERROR, "bindExpression", "unsupported window function " + name) end if
    arguments = []
    countStar = name == "COUNT" and len(expression.arguments) == 1 and ast.isStarExpression(expression.arguments[0])
    if not countStar then
      for each argumentAst in expression.arguments
        arguments = arguments + [bindExpressionInternal(argumentAst, sources, false, database)]
      end for
    end if
    if ranking and len(arguments) != 0 then return fail(BINDING_ERROR, "bindExpression", name + " takes no arguments") end if
    if isWindowAggregateName(name) and not countStar and len(arguments) != 1 then return fail(BINDING_ERROR, "bindExpression", name + " window requires one argument") end if
    if name == "NTILE" and (len(arguments) != 1 or not types.isIntegralKind(arguments[0].typeInfo.kind)) then return fail(TYPE_MISMATCH, "bindExpression", "NTILE requires one integral bucket count") end if
    if (name == "LAG" or name == "LEAD") and (len(arguments) < 1 or len(arguments) > 3) then return fail(BINDING_ERROR, "bindExpression", name + " requires value, optional offset, and optional default") end if
    if (name == "LAG" or name == "LEAD") and len(arguments) >= 2 and not types.isIntegralKind(arguments[1].typeInfo.kind) then return fail(TYPE_MISMATCH, "bindExpression", name + " offset must be integral") end if
    if (name == "LAG" or name == "LEAD") and len(arguments) == 3 and not types.comparable(arguments[0].typeInfo, arguments[2].typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", name + " default is incompatible with its value") end if
    if (name == "FIRST_VALUE" or name == "LAST_VALUE") and len(arguments) != 1 then return fail(BINDING_ERROR, "bindExpression", name + " requires one value") end if
    if name == "NTH_VALUE" and (len(arguments) != 2 or not types.isIntegralKind(arguments[1].typeInfo.kind)) then return fail(TYPE_MISMATCH, "bindExpression", "NTH_VALUE requires a value and integral position") end if
    partitions = []
    for each partitionAst in expression.partitionBy
      partitions = partitions + [bindExpressionInternal(partitionAst, sources, false, database)]
    end for
    orders = []
    descending = []
    nullsFirst = []
    nullsSpecified = []
    for each orderItem in expression.orderBy
      orders = orders + [bindExpressionInternal(orderItem.expression, sources, false, database)]
      descending = descending + [orderItem.descending]
      nullsFirst = nullsFirst + [orderItem.nullsFirst]
      nullsSpecified = nullsSpecified + [orderItem.nullsSpecified]
    end for
    if navigation and len(orders) == 0 then return fail(BINDING_ERROR, "bindExpression", name + " requires ORDER BY") end if
    resultType = types.create(types.SqlTypeKind.BigInt, 0, 0, 0, false)
    if name == "PERCENT_RANK" or name == "CUME_DIST" then resultType = types.create(types.SqlTypeKind.Double, 0, 0, 0, false) end if
    if name == "LAG" or name == "LEAD" or name == "FIRST_VALUE" or name == "LAST_VALUE" or name == "NTH_VALUE" then resultType = resultTypeWithNullability(arguments[0].typeInfo, true) end if
    if isWindowAggregateName(name) then
      pseudo = ast.functionExpression(name, expression.arguments, false)
      aggregateValue = bindAggregate(pseudo, sources, database)
      resultType = aggregateValue.typeInfo
    end if
    return expressions.window(name, arguments, partitions, orders, descending, nullsFirst, nullsSpecified, resultType)
  end if
  if ast.isFunctionExpression(expression) then
    if isScalarFunctionName(expression.name) then return bindScalarFunction(expression, sources, allowAggregates, database) end if
    if not allowAggregates then return fail(BINDING_ERROR, "bindExpression", "aggregate is not allowed in this clause") end if
    return bindAggregate(expression, sources, database)
  end if
  if ast.isCaseExpression(expression) then
    branches = []
    resultType = void
    hasConcrete = false
    for each branchAst in expression.branches
      condition = ensureBoolean(bindExpressionInternal(branchAst.condition, sources, allowAggregates, database), "bindExpression.CASE")
      result = bindExpressionInternal(branchAst.result, sources, allowAggregates, database)
      merged = mergeResultType(resultType, hasConcrete, result)
      resultType = merged[0]
      hasConcrete = merged[1]
      branches = branches + [expressions.caseBranch(condition, result)]
    end for
    elseExpression = void
    if expression.elseExpression is not void then
      elseExpression = bindExpressionInternal(expression.elseExpression, sources, allowAggregates, database)
      merged = mergeResultType(resultType, hasConcrete, elseExpression)
      resultType = merged[0]
      hasConcrete = merged[1]
    else
      resultType = resultTypeWithNullability(resultType, true)
    end if
    return expressions.caseExpression(branches, elseExpression, resultType)
  end if
  if ast.isCastExpression(expression) then
    operand = bindExpressionInternal(expression.operand, sources, allowAggregates, database)
    targetType = types.fromTypeName(expression.targetType, operand.typeInfo.nullable or isNullBoundLiteral(operand))
    return expressions.castExpression(operand, targetType)
  end if
  if ast.isInExpression(expression) then
    operand = bindExpressionInternal(expression.operand, sources, allowAggregates, database)
    candidates = []
    for each candidateAst in expression.values
      candidate = bindExpressionInternal(candidateAst, sources, allowAggregates, database)
      if not isNullBoundLiteral(operand) and not isNullBoundLiteral(candidate) and not types.comparable(operand.typeInfo, candidate.typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", "IN candidate is incompatible with operand") end if
      candidates = candidates + [candidate]
    end for
    return expressions.inPredicate(operand, candidates, expression.negated)
  end if
  if ast.isBetweenExpression(expression) then
    operand = bindExpressionInternal(expression.operand, sources, allowAggregates, database)
    lower = bindExpressionInternal(expression.lower, sources, allowAggregates, database)
    upper = bindExpressionInternal(expression.upper, sources, allowAggregates, database)
    if not isNullBoundLiteral(operand) and not isNullBoundLiteral(lower) and not types.comparable(operand.typeInfo, lower.typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", "BETWEEN lower bound is incompatible") end if
    if not isNullBoundLiteral(operand) and not isNullBoundLiteral(upper) and not types.comparable(operand.typeInfo, upper.typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", "BETWEEN upper bound is incompatible") end if
    return expressions.betweenPredicate(operand, lower, upper, expression.negated)
  end if
  if ast.isTruthTestExpression(expression) then
    operand = ensureBoolean(bindExpressionInternal(expression.operand, sources, allowAggregates, database), "bindExpression.truthTest")
    return expressions.truthTest(operand, expression.expected, expression.negated)
  end if
  if ast.isIsNullExpression(expression) then return expressions.isNull(bindExpressionInternal(expression.operand, sources, allowAggregates, database), expression.negated) end if
  if ast.isUnaryExpression(expression) then
    if expression.operator == "-" and ast.isLiteralExpression(expression.operand) and expression.operand.literalKind == ast.LITERAL_INTEGER and typeof(expression.operand.value) == "string" then
      signedValue = values.literalInteger("-" + expression.operand.value)
      return expressions.literal(signedValue, literalType(signedValue))
    end if
    operand = bindExpressionInternal(expression.operand, sources, allowAggregates, database)
    if expression.operator == "NOT" then
      ensureBoolean(operand, "bindExpression.NOT")
      return expressions.unary("NOT", operand, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, operand.typeInfo.nullable))
    end if
    if expression.operator == "+" or expression.operator == "-" then
      if not types.isNumeric(operand.typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", "unary numeric operator requires number") end if
      return expressions.unary(expression.operator, operand, operand.typeInfo)
    end if
    return fail(BINDING_ERROR, "bindExpression", "unsupported unary operator " + expression.operator)
  end if
  if ast.isBinaryExpression(expression) then
    left = bindExpressionInternal(expression.left, sources, allowAggregates, database)
    right = bindExpressionInternal(expression.right, sources, allowAggregates, database)
    operator = expression.operator
    if operator == "AND" or operator == "OR" then
      ensureBoolean(left, "bindExpression.logical.left")
      ensureBoolean(right, "bindExpression.logical.right")
      return expressions.binary(operator, left, right, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, left.typeInfo.nullable or right.typeInfo.nullable))
    end if
    if operator == "+" or operator == "-" or operator == "*" or operator == "/" or operator == "%" then
      if not types.isNumeric(left.typeInfo) or not types.isNumeric(right.typeInfo) then return fail(TYPE_MISMATCH, "bindExpression", "arithmetic requires numeric operands") end if
      resultType = types.commonNumeric(left.typeInfo, right.typeInfo)
      if operator == "/" then resultType = types.create(types.SqlTypeKind.Double, 0, 0, 0, resultType.nullable) end if
      return expressions.binary(operator, left, right, resultType)
    end if
    if operator == "||" then
      if not types.isTextKind(left.typeInfo.kind) or not types.isTextKind(right.typeInfo.kind) then return fail(TYPE_MISMATCH, "bindExpression", "|| requires text operands") end if
      return expressions.binary(operator, left, right, types.create(types.SqlTypeKind.Text, 0, 0, 0, left.typeInfo.nullable or right.typeInfo.nullable))
    end if
    if operator == "LIKE" or operator == "NOT LIKE" then
      if not types.isTextKind(left.typeInfo.kind) or not types.isTextKind(right.typeInfo.kind) then return fail(TYPE_MISMATCH, "bindExpression", "LIKE requires text operands") end if
      return expressions.binary(operator, left, right, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, left.typeInfo.nullable or right.typeInfo.nullable))
    end if
    if operator == "=" or operator == "<>" or operator == "!=" or operator == "<" or operator == "<=" or operator == ">" or operator == ">=" then
      comparable = false
      if isNullBoundLiteral(left) or isNullBoundLiteral(right) then comparable = true else comparable = types.comparable(left.typeInfo, right.typeInfo) end if
      if not comparable then return fail(TYPE_MISMATCH, "bindExpression", "comparison operands are incompatible") end if
      return expressions.binary(operator, left, right, types.create(types.SqlTypeKind.Boolean, 0, 0, 0, left.typeInfo.nullable or right.typeInfo.nullable))
    end if
    return fail(BINDING_ERROR, "bindExpression", "unsupported binary operator " + operator)
  end if
  return fail(INVALID_ARGUMENT, "bindExpression", "value is not an AST expression")
end function

