  return columns + [metadata.createColumn(len(columns) + 1, name, kind, nullable, 0, 0, 0)]
end function

// Builds the stable SQL-visible shape for a supported INFORMATION_SCHEMA relation.
function informationSchemaTable(name)
  columns = []
  relationKind = 0
  if name == "information_schema.schemata" then
    relationKind = INFORMATION_SCHEMATA
    columns = appendInformationColumn(columns, "schema_name", types.SqlTypeKind.Text, false)
  else if name == "information_schema.tables" then
    relationKind = INFORMATION_TABLES
    columns = appendInformationColumn(columns, "table_schema", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "table_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "table_type", types.SqlTypeKind.Text, false)
  else if name == "information_schema.columns" then
    relationKind = INFORMATION_COLUMNS
    columns = appendInformationColumn(columns, "table_schema", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "table_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "column_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "ordinal_position", types.SqlTypeKind.Integer, false)
    columns = appendInformationColumn(columns, "data_type", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "is_nullable", types.SqlTypeKind.Text, false)
  else if name == "information_schema.table_constraints" then
    relationKind = INFORMATION_TABLE_CONSTRAINTS
    columns = appendInformationColumn(columns, "table_schema", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "table_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "constraint_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "constraint_type", types.SqlTypeKind.Text, false)
  else if name == "information_schema.views" then
    relationKind = INFORMATION_VIEWS
    columns = appendInformationColumn(columns, "table_schema", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "table_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "view_definition", types.SqlTypeKind.Text, false)
  else if name == "information_schema.routines" then
    relationKind = INFORMATION_ROUTINES
    columns = appendInformationColumn(columns, "routine_schema", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "routine_name", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "routine_type", types.SqlTypeKind.Text, false)
    columns = appendInformationColumn(columns, "routine_definition", types.SqlTypeKind.Text, false)
  end if
  if relationKind == 0 then return void end if
  return [metadata.createTable(0, name, 1, columns), BoundInformationSchemaSource(relationKind)]
end function

// Appends resolved source using the supplied inputs.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function appendResolvedSource(sources, database, name, alias, availableQueries, viewStack)
  informationSource = informationSchemaTable(name)
  if informationSource is not void then
    visible = name
    if alias is not void then visible = alias else visible = sourceVisibleName(BoundSource(informationSource[0], void, 0, informationSource[1])) end if
    for each existing in sources
      if sourceVisibleName(existing) == visible then return fail(BINDING_ERROR, "appendResolvedSource", "duplicate table name or alias " + visible) end if
    end for
    return sources + [BoundSource(informationSource[0], alias, sourceWidth(sources), informationSource[1])]
  end if
  table = catalog.findTable(database, name)
  if table is not void then return appendSource(sources, table, alias) end if
  named = resolveNamedQuery(database, name, availableQueries, viewStack)
  if named is void then return fail(OBJECT_NOT_FOUND, "appendResolvedSource", "table or view not found: " + name) end if
  return appendNamedSource(sources, named, alias)
end function

// Finds bound column using the supplied inputs.
// Requires arguments that satisfy the validation performed below.
// Returns the computed value or operation status.
// Any side effects are limited to the explicitly invoked dependencies.
function findBoundColumn(sources, expression)
  if typeof(sources) != "array" or not ast.isColumnExpression(expression) then return fail(INVALID_ARGUMENT, "findBoundColumn", "invalid arguments") end if
  matchSource = void
  matchIndex = -1
  for each source in sources
    qualifierMatches = true
    if expression.qualifier is not void then
      qualifierMatches = expression.qualifier == sourceVisibleName(source) or expression.qualifier == source.table.name
    end if
    if qualifierMatches then
      localIndex = findColumnIndex(source.table, expression.name)
      if localIndex >= 0 then
        if matchSource is not void then return fail(BINDING_ERROR, "findBoundColumn", "ambiguous column " + expression.name) end if
        matchSource = source
        matchIndex = localIndex
      end if
    end if
  end for
  if matchSource is void then
    if expression.qualifier is not void then return fail(OBJECT_NOT_FOUND, "findBoundColumn", "unknown qualified column " + expression.qualifier + "." + expression.name) end if
    return fail(OBJECT_NOT_FOUND, "findBoundColumn", "unknown column " + expression.name)
  end if
  return [matchSource.offset + matchIndex, matchSource.table.columns[matchIndex]]
end function

